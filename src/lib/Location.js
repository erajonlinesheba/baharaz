export function getDeliveryCharge(division, district, sellerDivision, country) {
  // ALL WORLD REAL - Bangladesh hole BD charge, bidesh hole country charge
  if (country && country.toLowerCase()!== 'bangladesh') {
    const c = WORLD_COUNTRIES[country] || WORLD_COUNTRIES[country?.trim()]
    if (c) return c.charge
    return 1500 // International default
  }
  // BD logic - 100% genuine - Business loss hobe na
  if (!division &&!district) return 60
  const div = (division||'').toLowerCase()
  const dist = (district||'').toLowerCase()

  if (sellerDivision) {
    const sDiv = sellerDivision.toLowerCase()
    if (dist && sDiv.includes(dist)) return 60 // Same district
    if (div && sDiv === div) return 80 // Same division
  }

  for (let [dName, dInfo] of Object.entries(BD_FULL_DATA)) {
    if (dName.toLowerCase() === div) return dInfo.charge
    for (let distName of Object.keys(dInfo.districts)) {
      if (distName.toLowerCase() === dist) return dInfo.charge
    }
  }
  return 120 // Outside default
}

export function isBangladeshLocation(address, displayName) {
  const txt = (JSON.stringify(address||{}) + ' ' + (displayName||'')).toLowerCase()
  // Vietnam block - 100% real
  if (txt.includes('vietnam') || txt.includes('hưng yên') || txt.includes('thái bình') || txt.includes('đường') || txt.includes('vũ phúc') || txt.includes('đoàn')) {
    return false
  }
  // BD check
  if (txt.includes('bangladesh') || txt.includes('bangladesh') || txt.includes(' bd ')) return true
  for (let div of Object.keys(BD_FULL_DATA)) {
    if (txt.includes(div.toLowerCase())) return true
  }
  for (let dInfo of Object.values(BD_FULL_DATA)) {
    for (let dist of Object.keys(dInfo.districts)) {
      if (txt.includes(dist.toLowerCase())) return true
    }
  }
  return false
}

